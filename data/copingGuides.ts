/**
 * เลือกวิธีที่ควรเสนอ เมื่อเด็กติ๊กหัวข้อย่อยไว้หลายข้อ
 *
 * ยึดข้อที่หนักที่สุดเป็นตัวตั้ง ไม่ใช่ข้อที่ติ๊กก่อน — คนที่ทั้งโดนล้อและโดนดักตี
 * ต้องได้เห็นวิธีขอความช่วยเหลือ ไม่ใช่วิธีตอบนิ่ง ๆ ใส่คนล้อ
 */
export function guideForSubtopics(
  ids: string[] | undefined,
  weightOf: (id: string) => number,
): Guide | null {
  if (!ids?.length) return null;
  const worst = [...ids].sort((a, b) => weightOf(b) - weightOf(a))[0];
  const guideId = SUBTOPIC_TO_GUIDE[worst];
  return guideId ? (GUIDE_BY_ID[guideId] ?? null) : null;
}
