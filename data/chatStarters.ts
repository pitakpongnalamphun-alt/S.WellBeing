/**
 * ปุ่มเริ่มบทสนทนากับน้องปุย — ไม่ได้มีไว้ให้สะดวก แต่มีไว้บอกว่า "เรื่องแค่นี้ก็เล่าได้"
 *
 * เด็กที่กดเข้ามาแล้วเจอกล่องเปล่ามักปิดทิ้ง เพราะไม่รู้ว่าเรื่องของตัวเอง "ใหญ่พอ"
 * หรือเปล่า ปุ่มพวกนี้ตอบคำถามนั้นให้ก่อนที่เขาจะต้องถาม
 *
 * "ไม่รู้จะเริ่มยังไง" คือปุ่มที่จำเป็นที่สุดในห้าปุ่ม — มันอนุญาตให้เด็กที่ยังไม่มีคำพูด
 * ได้เริ่มโดยไม่ต้องมีคำพูด ห้ามตัดออกเวลาปรับรายการนี้
 *
 * กดแล้วส่งเป็นข้อความของนักเรียนเอง ไม่ใช่เมนูที่กดแล้วได้คำตอบสำเร็จรูป —
 * บทสนทนาต้องยังเป็นของเขา
 *
 * ย้ายออกมาจาก ChatScreen เพราะการ์ดบนหน้าแรกก็โชว์ปุ่มพวกนี้แล้ว ถ้าต่างคนต่าง
 * เขียนรายการของตัวเอง วันหนึ่งสองที่จะชวนคุยคนละเรื่อง และรายการบนหน้าแรกอาจ
 * หลุด "ไม่รู้จะเริ่มยังไง" ไปโดยไม่มีใครสังเกต
 */
export const CHAT_STARTERS = [
  "วันนี้เหนื่อยมาก",
  "อยากระบายเฉย ๆ",
  "ทะเลาะกับเพื่อน",
  "ที่บ้านกดดัน",
  "ไม่รู้จะเริ่มยังไง",
] as const;

/**
 * ชุดที่โชว์บนการ์ดหน้าแรก — สั้นกว่าเพราะพื้นที่น้อยกว่า
 * เอา "ไม่รู้จะเริ่มยังไง" ติดมาด้วยเสมอ ด้วยเหตุผลข้างบน
 */
export const HOME_STARTERS: readonly string[] = [
  "วันนี้เหนื่อยมาก",
  "อยากระบายเฉย ๆ",
  "ไม่รู้จะเริ่มยังไง",
];

/**
 * ข้อความจาก ?q= ใช้ได้ไหม
 *
 * รับเฉพาะที่ตรงกับรายการนี้เป๊ะ ๆ ไม่รับข้อความอิสระ เพราะถ้ารับอะไรก็ได้ ใครส่งลิงก์
 * ?q=<ข้อความ> ให้เด็กกด ระบบจะพิมพ์ประโยคนั้น "ในนามของเด็ก" แล้วส่งเข้าห้องแชท
 * ทันที คำที่เด็กไม่ได้พูดจะกลายเป็นคำของเด็กในบทสนทนาที่ปุยตอบกลับ และถูกเก็บลง
 * เครื่องเป็นบทสนทนาของเขาไปเลย
 */
export function isAllowedStarter(q: string | null | undefined): q is string {
  return !!q && (CHAT_STARTERS as readonly string[]).includes(q);
}
