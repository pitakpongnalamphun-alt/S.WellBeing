const TONE = {
  do: { ring: "ring-mint-200", bg: "bg-mint-50/60", ink: "text-mint-800", Icon: Check },
  dont: { ring: "ring-rose-200", bg: "bg-rose-50/60", ink: "text-rose-800", Icon: Ban },
  warn: { ring: "ring-amber-200", bg: "bg-amber-50/60", ink: "text-amber-900", Icon: AlertTriangle },
} as const;

function BlockList({ block }: { block: Block }) {
  const t = TONE[block.tone ?? "do"];
  return (
    <div className={`rounded-2xl ${t.bg} p-4 ring-1 ${t.ring}`}>
      <p className={`flex items-center gap-2 text-[0.92rem] font-bold ${t.ink}`}>
        <t.Icon className="size-4 shrink-0" aria-hidden="true" />
        {block.title}
      </p>
      <ul className="mt-2.5 space-y-2">
        {block.items.map((it) => (
          <li key={it} className="flex gap-2 text-[0.86rem] leading-[1.9] text-ink-soft">
            <span className="mt-[0.7em] size-1 shrink-0 rounded-full bg-current opacity-40" aria-hidden="true" />
            {it}
          </li>
        ))}
      </ul>
    </div>
  );
}

